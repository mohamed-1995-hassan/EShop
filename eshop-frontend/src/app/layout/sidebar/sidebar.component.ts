  toggleSubmenu(route: string) {
    this.openSubmenus.update(submenus => {
      const newSubmenus = new Set(submenus);
      if (newSubmenus.has(route)) {
        newSubmenus.delete(route);
      } else {
        newSubmenus.add(route);
      }
      return newSubmenus;
    });
  }

  isSubmenuOpen(route: string): boolean {
    return this.openSubmenus().has(route);
  }
